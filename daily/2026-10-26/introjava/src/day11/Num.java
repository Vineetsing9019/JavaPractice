	package day11;

	public class Num {

	    public static void main(String[] args) {

	        for (int i = 4; i >= 1; i--) {   // Outer loop

	            for (int j = 1; j <= 4; j++) {   // Inner loop

	                System.out.print(i);
	            }

	            System.out.println();
	        }
	    }
	}


