package day11;

public class NestedLoop {
	 public static void main(String[] args) {

	        for (int i = 1; i <= 3; i++) {

	            for (int j = 11; j <= 13; j++) {

	                System.out.print(j + " ");
	            }

	            System.out.println();
	        }
	    } 

}

