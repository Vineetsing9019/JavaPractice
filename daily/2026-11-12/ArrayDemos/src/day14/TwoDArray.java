package day14;

public class TwoDArray {

    public static void main(String[] args) {

        int[][] values = {
                {11, 12, 13, 14, 15},
                {21, 22, 23, 24, 25}
        };

        System.out.println(values[1][0]); // 11
        System.out.println(values[0][2]); // 25

    }
}
