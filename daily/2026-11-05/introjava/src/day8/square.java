package day8;


import java.util.Scanner;

public class square {
    public static void main(String[] args) {

        Scanner sc = new Scanner(System.in);

        System.out.print("Enter a number: ");
        int num = sc.nextInt();

        for (int i = 1; i <= 1; i++) {
            System.out.println(num + " * " + num + " = " + (num * num));
        }

        sc.close();
    }
}

